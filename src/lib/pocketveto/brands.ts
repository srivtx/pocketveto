/* Logo lookup                                                         */

const LOOKUP: { id: string; needles: string[]; logo: BrandLogo }[] = BRANDS.flatMap((b) =>
  b.logo
    ? [{ id: b.id, needles: [...b.fragments, ...(b.aliases ?? []), b.name.toUpperCase()], logo: b.logo }]
    : []
);

/**
 * Which brand mark should sit on a card for this text? Matches the item's
 * display name and (when available) the raw merchant key — statement
 * charges keep their evidence, cards keep their identity.
 *
 * Longest needle wins, so specific brands beat their generic fragments:
 * “Disney+ Hotstar” is Hotstar, not Disney+.
 */
export function logoIdFor(...texts: string[]): string | null {
  const hay = texts.filter(Boolean).join(' ').toUpperCase();
  if (!hay) return null;
  let best: string | null = null;
  let bestLen = 0;
  for (const { id, needles } of LOOKUP) {
    const hit = needles.find((n) => n.length > bestLen && hay.includes(n));
    if (hit) {
      best = id;
      bestLen = hit.length;
    }
  }
  return best;
}

/** The logo data for a brand id (undefined → no mark, use the kind glyph). */
export function logoById(id: string | null): BrandLogo | undefined {
  if (!id) return undefined;
  return LOOKUP.find((l) => l.id === id)?.logo;
}
