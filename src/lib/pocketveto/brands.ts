/**
 * PocketVeto — the brand registry.
 *
 * One place for everything brand-shaped: the statement-parser's known-brand
 * fragments (moved here from scan.ts — parse behavior unchanged), plus the
 * display mark each recognized brand carries on its card.
 *
 * The marks are embedded simple-icons path data (CC0) and hand-drawn
 * fallbacks — never fetched. This app promises "no server, nowhere to
 * phone home"; brand logos are no excuse to break it.
 *
 * Logo rules:
 *  - A real logo only when its glyph still reads at tile size (a 24x24
 *    viewBox rendered ~20px). Dense wordmarks get a clean letter instead.
 *  - Tile = the brand's color with a white mark; light brand colors and
 *    black brands get a near-white tile with an ink mark.
 *  - logoOnly entries never touch parsing — grouped catalog entries keep
 *    their group name, the tile still shows the real brand.
 *  - Lookup is longest-needle-wins: "Disney+ Hotstar" resolves to the
 *    Hotstar mark, not the Disney one.
 */

import type { ItemKind } from './types';

export interface BrandLogo {
  /** simple-icons 24x24 path (CC0) or a hand-drawn mark — embedded, local. */
  path?: string;
  /** Clean letter when no glyph reads at tile size. */
  letter?: string;
  /** Tile background color. */
  color: string;
  /** 'ink' → dark mark on the tile (light brand colors). Default: white. */
  glyph?: 'ink';
}

export interface Brand {
  id: string;
  /** Raw merchant fragments — the statement parser's match keys. */
  fragments: string[];
  /** Display name the parser substitutes for the raw merchant. */
  name: string;
  kind?: ItemKind;
  /** Extra display-name matches for the logo (never used for parsing). */
  aliases?: string[];
  /** True → logo-only: display mark, never a parse result. */
  logoOnly?: boolean;
  logo?: BrandLogo;
}

